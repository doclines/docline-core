/**
 * Derive an icon + CSS color variable from a link title and href.
 * Splits the href into path segments and the title into words,
 * then matches against SEGMENT_RULES.
 *
 * @param {string} title
 * @param {string} href
 * @returns {{ name: string, cssVar: string }}
 */
export function getDocIcon(title, href) {
  // Build a flat list of tokens from both the URL path and the title.
  // Normalise separators so "aiga-core" → ["aiga", "core"].
  const tokens = [
    ...(href || '').toLowerCase().replace(/[_-]/g, ' ').split(/[/\s.]+/),
    ...(title || '').toLowerCase().replace(/[_-]/g, ' ').split(/\W+/),
  ].filter(Boolean);

  for (const [keywords, iconName, cssVar] of SEGMENT_RULES) {
    if (tokens.some((tok) => keywords.some((kw) => tok.includes(kw)))) {
      return { name: iconName, cssVar };
    }
  }
  return { name: 'file', cssVar: '--icon-soft' };
}

/**
 * Render a Mintlify-style icon badge HTML string.
 * Uses CSS variables for color so it adapts to the current theme.
 *
 * @param {string} title
 * @param {string} href
 * @returns {string} HTML string
 */
export function renderIconBadge(title, href) {
  const { name, cssVar } = getDocIcon(title, href);
  const paths = ICONS[name] || ICONS.file;
  return (
    `<span class="card-icon-auto" style="color:var(${cssVar})">` +
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `width="20" height="20" aria-hidden="true">${paths}</svg>` +
    `</span>`
  );
}

/**
 * Render an icon badge from an explicit Mintlify icon name (e.g. "bolt", "brain").
 * Falls back to getDocIcon if the name is not in ICONS.
 *
 * @param {string} iconName   - Mintlify/Lucide icon name
 * @param {string} title      - card title (for fallback detection)
 * @param {string} href       - card href (for fallback detection)
 * @returns {string} HTML string
 */
export function renderNamedIconBadge(iconName, title, href) {
  // Map common Mintlify aliases to our icon names
  const aliases = {
    bolt: 'zap', 'file-code': 'file', gear: 'settings',
    'arrows-rotate': 'refresh', wand: 'zap', layer: 'layers',
    cubes: 'layers', sitemap: 'map', magnifying: 'map',
    clipboard: 'file', 'circle-check': 'shield', microchip: 'cpu',
    cloud: 'server', chart: 'layers', play: 'zap', wrench: 'wrench',
    key: 'shield', building: 'server', utensils: 'puzzle',
    robot: 'bot', star: 'zap', puzzle: 'puzzle', book: 'book',
    globe: 'globe', database: 'database', terminal: 'terminal',
    users: 'users', server: 'server', link: 'link',
    lock: 'shield', rocket: 'rocket',
  };

  const resolved = ICONS[iconName]
    ? iconName
    : aliases[iconName]
      ? aliases[iconName]
      : null;

  if (!resolved) return renderIconBadge(title, href);

  // Pick a CSS variable based on the resolved icon
  const colorMap = {
    bot: '--icon-primary', refresh: '--icon-primary', zap: '--icon-warm',
    brain: '--icon-warm', rocket: '--icon-primary', puzzle: '--icon-primary',
    settings: '--icon-soft', wrench: '--icon-warm', database: '--icon-warm',
    shield: '--icon-warm', terminal: '--icon-soft', laptop: '--icon-soft',
    cpu: '--icon-primary', layout: '--icon-soft', link: '--icon-primary',
    globe: '--icon-warm', layers: '--icon-warm', users: '--icon-warm',
    server: '--icon-warm', map: '--icon-primary', package: '--icon-soft',
    book: '--icon-warm', file: '--icon-muted',
  };

  const cssVar = colorMap[resolved] || '--icon-primary';
  const paths = ICONS[resolved];
  return (
    `<span class="card-icon-auto" style="color:var(${cssVar})">` +
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `width="20" height="20" aria-hidden="true">${paths}</svg>` +
    `</span>`
  );
}
